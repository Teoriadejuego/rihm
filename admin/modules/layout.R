teacher_panel_layout <- function() {
  div(class = "research-workbench",
    tags$a(class = "research-skip", href = "#teacher-main", "Skip to the workbench"),
    tags$header(class = "research-header",
      div(class = "research-mark", `aria-hidden` = "true", "R"),
      div(h1("Mini-dictator research lab"), p("Researcher and teacher workbench")),
      uiOutput("student_link")),
    div(id = "teacher-main", tabindex = "-1",
      bslib::navset_tab(id = "teacher_tabs", selected = "Project",
        bslib::nav_panel("Project",
          tags$section(class = "research-intro", h2("Six decisions, a shared investigation"),
            p(class = "research-lead", "How much would you give up for a more equal outcome? In the Mini-Dictator Game, students make six allocation decisions and then examine the choices of their class."),
            div(class = "research-split",
              div(h3("Prepare the activity"), p("One student chooses how to divide a payoff with an anonymous recipient. The recipient receives the allocation. Explain the roles and the incentives used in your class before anyone opens the survey.")),
              div(h3("Try one decision"), p("An equal split gives each person 10. The alternative gives the decision-maker 12 and the recipient 4. What changes for each person? What happens to their combined payoff?"))),
            h3("Run the class"),
            tags$ol(class = "research-sequence",
              tags$li(strong("Project. "), "Review the roles and the six allocation choices."),
              tags$li(actionLink("go_survey", "Survey QR"), "Project one invitation for the whole class and let students finish the survey."),
              tags$li(actionLink("go_update", "Update"), "Publish the results and wait for confirmation."),
              tags$li(actionLink("go_teach", "Teach"), "Project the slides and discuss the published group."),
              tags$li(actionLink("go_results", "Results QR"), "Share the student dashboard for independent comparisons.")),
            tags$details(tags$summary("Preview the six decisions"), teacher_html_table(teacher_payoffs(), "Payoffs for the decision-maker and recipient")),
            p(tags$a(href = "https://sites.google.com/view/rihm/intro-for-teachers/getting-prepared", target = "_blank", rel = "noopener", "Read the RIHM teacher preparation guide")),
            tags$details(tags$summary("Classification and interpretation"),
              p("Altruist, Egalitarian, Selfish and Antisocial are overlapping indicators among consistent responses. Inconsistent uses complete binary responses. Partial and non-binary responses are excluded; duplicate response IDs are resolved before analysis."),
              p("The original classification rules are preserved. These indicators describe response patterns, not personalities, and the reference samples are not representative national estimates.")),
            tags$details(tags$summary("About the RIHM project"),
              p("Through MissionLab, Universidad Loyola Andalucía in Spain, Ateneo de Manila University in the Philippines and Université Magis in Madagascar developed this classroom toolkit. Students use their own decisions to discuss inequality and the responsibilities of managers."),
              tags$a(href = "https://sites.google.com/view/rihm/about-us", target = "_blank", rel = "noopener", "Meet the project team")),
            p(class = "research-source", "Research foundation: ",
              tags$a(href = "https://doi.org/10.3389/fnbeh.2015.00287", target = "_blank", rel = "noopener", "Corgnet, Espín & Hernán-González (2015)")))),
        bslib::nav_panel("Survey QR",
          tags$section(class = "research-section survey-qr-workspace",
            div(class = "section-heading", h2("Invite the class"),
              p("Generate one QR for the whole group. Each scan opens the survey with the same class code.")),
            div(class = "survey-qr-toolbar",
              tags$button(type = "button", id = "generate_survey_qr", class = "btn btn-primary", "Generate QR"),
              div(id = "survey_qr_actions", hidden = NA,
                tags$button(type = "button", id = "present_survey_qr", class = "btn btn-outline-primary", "Project QR"),
                tags$button(type = "button", id = "download_survey_qr", class = "btn btn-outline-primary", "Download QR image"),
                tags$button(type = "button", id = "copy_survey_link", class = "btn btn-outline-primary", "Copy survey link"))),
            p(id = "survey_qr_status", role = "status", `aria-live` = "polite", class = "research-hint",
              "Generate a QR when the class is ready to start."),
            div(id = "surveyQrStage", class = "survey-qr-stage", tabindex = "-1",
              div(id = "survey_qr_empty", h3("One code, one class"),
                p("Your QR and class code will appear here.")),
              div(id = "survey_qr_ready", hidden = NA,
                h2("Scan to join the survey"),
                div(id = "survey_qr_image", class = "survey-qr-image"),
                p(class = "survey-qr-caption", tags$span("Code"), tags$strong(id = "survey_qr_code")),
                p(class = "survey-qr-instruction", "Open the survey with your camera. Make all six choices and submit your response."),
                tags$details(class = "survey-fallback", tags$summary("Joining without a camera?"),
                  p("Open the link shared by your teacher, or use this address on your device."),
                  tags$a(id = "survey_qr_link", target = "_blank", rel = "noopener noreferrer")),
                tags$button(type = "button", id = "exit_survey_qr", class = "btn btn-outline-primary", "Exit full screen"))),
            p(class = "research-hint", "Keep the same QR for the entire class. Generate a new QR only for a new group. Download the image before reloading or signing out; the panel does not save this code."),
            tags$details(tags$summary("How the class code is used"),
              p("The survey receives the code as Treatment_choice. Everyone using this QR shares that label in Qualtrics. The code is not an access password."),
              p("The student dashboard still uses the latest response hour in the database when you update and publish. Generating a QR does not change that selection or publish any results.")))),
        bslib::nav_panel("Update",
          tags$section(class = "research-section", div(class = "section-heading", h2("Update and publish"),
            p(class = "research-lead", "Wait until students have submitted their responses, then select Update and publish. Check the response window and sample size in Latest group before projecting the slides.")),
            div(class = "window-explanation", h3("The latest response defines the hour"),
              p("The latest valid EndDate in the class survey anchors a one-hour window. Selection happens before quality exclusions, so an older activity stays selected until newer responses arrive. No session code is required.")),
            uiOutput("connection_status"),
            div(class = "update-actions", actionButton("update_publish", "Update and publish", class = "btn-primary", disabled = TRUE),
              actionButton("cancel_operation", "Cancel pending publication", class = "btn-outline-secondary", disabled = TRUE)),
            div(class = "operation-status", role = "status", `aria-live` = "polite", textOutput("operation_status")),
            textOutput("cooldown_status"),
            p(class = "research-hint", "One operation runs at a time for all teacher sessions. Real updates have a shared three-minute cooldown, including after a server restart. If an update fails, students retain the last successful deployment."),
            hr(), h3("Practice privately"), p("Preview synthetic responses without downloading Qualtrics data or changing the student site."),
            actionButton("load_demo", "Load private demonstration", class = "btn-outline-primary", disabled = TRUE))),
        bslib::nav_panel("Teach",
          tags$section(class = "teach-workspace", div(class = "section-heading", h2("Teach the activity"),
            p("Twelve slides for projection. Presenter notes stay outside the projected stage.")),
            div(class = "presentation-toolbar",
              actionButton("slide_previous", "Previous"), uiOutput("slide_position", inline = TRUE),
              actionButton("slide_next", "Next"),
              tags$button(type = "button", id = "start_presentation", class = "btn btn-primary", "Present full screen"),
              actionButton("stop_presentation", "End presentation")),
            div(id = "presentationStage", class = "presentation-stage", tabindex = "0",
              uiOutput("projection_slide"),
              div(class = "projection-footer", textOutput("presentation_snapshot", inline = TRUE),
                tags$span("← → navigate · Esc exits full screen"))),
            div(class = "presenter-notes", h3("Private presenter notes"), textOutput("presenter_notes")),
            p(class = "research-hint", "Presenting pins the current publication. New results will not change the projected snapshot until you end presentation mode."))),
        bslib::nav_panel("Results QR",
          tags$section(class = "research-section", h2("Share the class results"),
            p("Students can scan the QR or open the link to explore the latest published group."),
            uiOutput("results_invitation"),
            h3("Discuss what you find"),
            p("Choose one indicator and compare your group with a reference country. Read both sample sizes. How might the people who took part influence the difference you see?"),
            p(tags$a(href = "https://sites.google.com/view/rihm/intro-for-teachers/promoting-reflection", target = "_blank", rel = "noopener", "More RIHM discussion prompts")))),
        bslib::nav_panel("Latest group",
          tags$section(class = "research-section", div(class = "section-heading", h2("Latest published group"),
            p("This view restores and checks the snapshot currently served by the student site when you sign in.")),
            actionButton("refresh_latest", "Reload published snapshot", class = "btn-outline-primary", disabled = TRUE),
            uiOutput("latest_summary"), uiOutput("latest_bars"),
            tags$details(tags$summary("Published behaviour cells"), tableOutput("latest_behaviours")),
            tags$details(tags$summary("Published compassion × envy cells"), tableOutput("latest_matrix")))),
        bslib::nav_panel("Diagnostics",
          tags$section(class = "research-section", div(class = "section-heading", h2("Private diagnostics"),
            p("Review the most recent candidate prepared in this session. Row-level responses are not shown or retained by this view.")),
            uiOutput("candidate_summary"), tableOutput("selection_diagnostics"), tableOutput("quality_diagnostics"),
            h3("Exact protected behaviour cells"), tableOutput("candidate_behaviours"),
            h3("Exact protected compassion × envy cells"), tableOutput("candidate_matrix")))
      )
    )
  )
}
